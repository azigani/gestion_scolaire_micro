package com.edumanager.hr.domain.employee.enums;

/**
 * Enum: EmployeeStatus
 * Represents the status of an employee.
 */
public enum EmployeeStatus {
    /**
     * Employee is currently active
     */
    ACTIVE,
    
    /**
     * Employee is on leave
     */
    ON_LEAVE,
    
    /**
     * Employee is suspended
     */
    SUSPENDED,
    
    /**
     * Employee has been terminated
     */
    TERMINATED,
    
    /**
     * Employee has resigned
     */
    RESIGNED
}
